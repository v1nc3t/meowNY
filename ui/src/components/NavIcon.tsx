/** An icon's pixels as one path: each run of pixels that are on in a row is a rectangle one pixel high. */
function pathOf(rows: string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) d += `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`
  })
  return d
}

const PATHS = Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [name, pathOf(rows)]))

/** The small pixel icons of the navigation and of icon buttons. Give a button's icon its own class: `nav-icon` hides on a narrow window. */
export default function NavIcon({ name, className = 'nav-icon' }: { name: string; className?: string }) {
  return (
    <svg className={className} viewBox="0 0 12 12" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true">
      <path d={PATHS[name] ?? ''} />
    </svg>
  )
}
